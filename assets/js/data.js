// Темп выпуска со слов заказчика: заказ около 10 домов идёт по 4–5 в месяц,
// заказ от 50 домов идёт по 10 в месяц. Между этими точками показываем вилку.
export function pace(n) {
  if (n <= 15) return { rate: '4–5 в месяц', min: Math.ceil(n / 5), max: Math.ceil(n / 4) };
  if (n < 50) return { rate: '5–10 в месяц', min: Math.ceil(n / 10), max: Math.ceil(n / 5) };
  return { rate: '10 в месяц', min: Math.ceil(n / 10), max: Math.ceil(n / 10) };
}
